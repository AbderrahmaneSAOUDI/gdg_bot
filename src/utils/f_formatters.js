/**
 * Resolves a Discord User ID into a human-readable display name.
 *
 * @param {import('discord.js').Guild} [guild]
 * @param {string} userId
 * @returns {string} e.g. "Nossiba BOUTEBBA"
 */
export function formatUserName(guild, userId) {
  if (!userId) return 'Unknown User';

  // 1. Check live Guild Member cache
  const member = guild?.members?.cache?.get(userId);
  if (member) {
    return member.displayName || member.user?.username || member.user?.tag || userId;
  }

  // 2. Check live Client User cache
  const user = guild?.client?.users?.cache?.get(userId);
  if (user) {
    return user.displayName || user.username || user.tag || userId;
  }

  // 3. Check known member directory
  if (KNOWN_MEMBERS[userId]) {
    return KNOWN_MEMBERS[userId].displayName;
  }

  // 4. Clean fallback without showing raw code tags
  return `User (${userId.slice(-4)})`;
}

/**
 * Resolves a Discord Role ID into its human-readable role name.
 *
 * @param {import('discord.js').Guild} [guild]
 * @param {string} roleId
 * @param {string} [fallbackName]
 * @returns {string} e.g. "EventX 3.0 - Team 01 - Mentor"
 */
export function formatRoleName(guild, roleId, fallbackName = 'Assigned Role') {
  if (!roleId) return fallbackName;

  const role = guild?.roles?.cache?.get(roleId);
  if (role) {
    return role.name;
  }

  if (KNOWN_ROLES[roleId]) {
    return KNOWN_ROLES[roleId];
  }

  return fallbackName;
}

/**
 * Resolves a Discord Channel ID into its human-readable channel name.
 *
 * @param {import('discord.js').Guild} [guild]
 * @param {string} channelId
 * @param {string} [fallbackName]
 * @returns {string} e.g. "#ex3・1・chat" or "🔊 ex3・1・room"
 */
export function formatChannelName(guild, channelId, fallbackName = 'channel') {
  if (!channelId) return fallbackName;

  const channel = guild?.channels?.cache?.get(channelId);
  if (channel) {
    const prefix = channel.isVoiceBased?.() ? '🔊 ' : '#';
    return `${prefix}${channel.name}`;
  }

  if (KNOWN_CHANNELS[channelId]) {
    const entry = KNOWN_CHANNELS[channelId];
    const prefix = entry.type === 'voice' ? '🔊 ' : '#';
    return `${prefix}${entry.name}`;
  }

  return fallbackName.startsWith('#') || fallbackName.startsWith('🔊')
    ? fallbackName
    : `#${fallbackName}`;
}

